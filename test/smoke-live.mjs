/** Verificação do site publicado, só leitura (não envia RSVP nem recados).  BASE=https://… node test/smoke-live.mjs */
import { createRequire } from "node:module";
import fs from "node:fs";
const { chromium, devices } = createRequire(import.meta.url)("playwright");
const B = process.env.BASE || "https://universo.moshikg10.workers.dev";
const OUT = new URL("./shots/", import.meta.url).pathname; fs.mkdirSync(OUT, { recursive: true });
const W = ms => new Promise(r => setTimeout(r, ms));
const errs = []; let fails = 0;
const ok = (c, m) => { console.log((c ? "ok    " : "FALHA ") + m); if (!c) fails++; };
const b = await chromium.launch();
const c = await b.newContext({ ...devices["iPhone 13"] }); const p = await c.newPage();
p.on("pageerror", e => errs.push(e.message));
// o 401 de /api/me antes do login é esperado (o painel mostra a tela de entrada)
p.on("console", m => { if (m.type() === "error" && !/fonts\.g|401 \(Unauthorized\)/.test(m.text())) errs.push(m.text()); });
await p.goto(B + "/", { waitUntil: "networkidle" }); await W(800);
ok((await p.locator("h1").innerText()).includes("Seu casamento"), "landing no ar");
await p.screenshot({ path: OUT + "live-landing.png" });
await p.goto(B + "/c/petala-e-lucas", { waitUntil: "networkidle" }); await W(1800);
ok(await p.locator(".hero-logo").isVisible(), "site de Pétala & Lucas com o logo");
ok(await p.evaluate(() => document.fonts.check('40px "TrashHand"')), "fonte manuscrita carregada");
ok(await p.locator(".step").count() === 7, "cronograma com 7 momentos");
await p.screenshot({ path: OUT + "live-petalucas.png" });
await p.goto(B + "/i/exemplo-petala-e-lucas-2027", { waitUntil: "networkidle" }); await W(800);
await p.click("#open"); await W(2600);
ok(await p.locator(".inv-head").isVisible(), "convite abre");
await p.screenshot({ path: OUT + "live-convite.png" });
await p.goto(B + "/painel", { waitUntil: "networkidle" }); await W(600);
await p.click("#fill"); await W(2000);
ok(await p.locator(".hello h1").count() === 1, "painel de demonstração entra");
await p.screenshot({ path: OUT + "live-painel.png" });
await b.close();
ok(errs.length === 0, "sem erros no console" + (errs.length ? ": " + errs.join(" | ") : ""));
process.exitCode = fails ? 1 : 0;
